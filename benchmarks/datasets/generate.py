#!/usr/bin/env python3
"""Regenerate public synthetic fixtures and their manifest. Requires Pillow."""
import hashlib
import json
from pathlib import Path
import time
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'synthetic'
OUT.mkdir(exist_ok=True)
LATIN = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
CJK = '/usr/share/fonts/truetype/arphic/uming.ttc'

def font(path, size):
    return ImageFont.truetype(path, size)

def page(size, lines, font_path=LATIN, point=42):
    image = Image.new('RGB', size, 'white')
    draw = ImageDraw.Draw(image)
    for i, line in enumerate(lines):
        draw.text((48, 45 + i * (point + 25)), line, fill='black', font=font(font_path, point))
    return image

specs = [
    ('english-print', 'english_print.png', 'english_print', (900, 360),
     ['GB10 Synthetic OCR Benchmark', 'Open source document sample', 'Invoice total: USD 123.45'], LATIN, 38),
    ('chinese-print', 'chinese_print.png', 'chinese_print', (1000, 450),
     ['合成中文打印文档', '项目名称：光学字符识别', '日期：二零二六年十一月'], CJK, 46),
    ('paragraph-layout', 'paragraph_layout.png', 'multi_paragraph', (1100, 650),
     ['Research Notes', 'Paragraph one: This is a synthetic document.',
      'It has several lines of printed text.', '', 'Methods',
      'Paragraph two: Layout and spacing vary.', 'All content is fictional.'], LATIN, 32),
    ('math-expression', 'math_expression.png', 'math_expression', (900, 360),
     ['Simple expressions', 'x^2 + y^2 = z^2', '2 + 3 = 5'], LATIN, 42),
    ('small-resolution', 'small_resolution.png', 'resolution_small', (640, 240),
     ['Low resolution sample', 'GB10 OCR 2026'], LATIN, 32),
    ('large-resolution', 'large_resolution.png', 'resolution_large', (1600, 900),
     ['High resolution sample', 'GB10 OCR 2026', 'Synthetic printed text'], LATIN, 58),
]
entries = []
for sample_id, filename, category, size, lines, font_path, point in specs:
    image = page(size, lines, font_path, point)
    path = OUT / filename
    image.save(path, format='PNG', optimize=False, compress_level=9)
    entries.append({'id': sample_id, 'path': f'synthetic/{filename}', 'file_type': 'png',
                    'file_type_code': 1, 'width': size[0], 'height': size[1], 'bytes': path.stat().st_size,
                    'pages': 1, 'category': category, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                    'source': 'Generated by benchmarks/datasets/generate.py; fictional text',
                    'license': 'MIT (repository); rendered DejaVu Sans or AR PL UMing font'})
pdf_pages = [page((850, 1100), ['Synthetic PDF - Page 1', 'GB10 OCR benchmark', 'No personal information'], LATIN, 34),
             page((850, 1100), ['Synthetic PDF - Page 2', 'Second printed page', 'Open test fixture'], LATIN, 34)]
single_pdf_path = OUT / 'one_page.pdf'
single_stamp = time.strptime('20261110162314', '%Y%m%d%H%M%S')
pdf_pages[0].save(single_pdf_path, 'PDF', resolution=72.0, title='one_page',
                  creationDate=single_stamp, modDate=single_stamp)
entries.append({'id': 'one-page-pdf', 'path': 'synthetic/one_page.pdf', 'file_type': 'pdf',
                'file_type_code': 0, 'width': 850, 'height': 1100, 'bytes': single_pdf_path.stat().st_size,
                'pages': 1, 'category': 'single_page_pdf', 'sha256': hashlib.sha256(single_pdf_path.read_bytes()).hexdigest(),
                'source': 'Generated by benchmarks/datasets/generate.py; fictional text',
                'license': 'MIT (repository); rendered DejaVu Sans font'})
pdf_path = OUT / 'two_page.pdf'
double_stamp = time.strptime('20261110155007', '%Y%m%d%H%M%S')
pdf_pages[0].save(pdf_path, 'PDF', save_all=True, append_images=pdf_pages[1:], resolution=72.0,
                  title='two_page', creationDate=double_stamp, modDate=double_stamp)
entries.append({'id': 'two-page-pdf', 'path': 'synthetic/two_page.pdf', 'file_type': 'pdf',
                'file_type_code': 0, 'width': 850, 'height': 1100, 'bytes': pdf_path.stat().st_size,
                'pages': 2, 'category': 'multi_page_pdf', 'sha256': hashlib.sha256(pdf_path.read_bytes()).hexdigest(),
                'source': 'Generated by benchmarks/datasets/generate.py; fictional text',
                'license': 'MIT (repository); rendered DejaVu Sans font'})
(ROOT / 'manifest.json').write_text(json.dumps({'schema_version': 1, 'samples': entries}, indent=2, ensure_ascii=False) + '\n')
print(f'Generated {len(entries)} synthetic samples')
